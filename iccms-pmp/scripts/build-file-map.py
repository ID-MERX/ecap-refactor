#!/usr/bin/env python3
"""Build the "Appendix: legacy file -> module map" table for docs/AUDIT.md from the
"Legacy files" tables of docs/audit/<module>.md.

Keeping it generated means the appendix cannot drift from the module files: every file a module
audit declares is mapped, and every module that declares it is listed against that file.

Usage:
    python3 scripts/build-file-map.py            # print the markdown table
    python3 scripts/build-file-map.py --write    # splice it into AUDIT.md section 8
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AUDIT = ROOT / "docs" / "AUDIT.md"
MODULE_DIR = ROOT / "docs" / "audit"

ROW = re.compile(r"^\|\s*(?P<file>[^|]+?)\s*\|\s*(?P<lines>[^|]*?)\s*\|\s*(?P<role>.*?)\s*\|\s*$")

# Modules whose legacy files belong to the shell / cross-cutting layer rather than a route.
SHELL = {"shell"}


def clean_file(cell: str) -> str | None:
    """Extract the first backticked path from a Legacy files cell."""
    m = re.search(r"`(?:legacy:)?([A-Za-z0-9_@./-]+\.[A-Za-z0-9]+)`", cell)
    if not m:
        return None
    value = m.group(1).strip()
    if "legacy:" in cell and value.split(":")[0] in {"backend", "legacy"}:
        return None
    # A cell may name one path and cite line numbers after it (e.g. `src/x.tsx:1-20`).
    value = value.split(":")[0]
    is_backend = "backend:" in (re.search(r"`([^`]+)`", cell).group(1) if re.search(r"`([^`]+)`", cell) else "")
    if is_backend:
        return "backend:" + value.removeprefix("backend:")
    if "/" not in value and not value.endswith((".ts", ".tsx", ".js", ".json", ".md", ".html")):
        return None
    if value.startswith(("src/", "index.html", "vite.config", "FY_FILTER", "scripts/")):
        return value
    # Allow bare names like App.tsx / index.html.
    if re.search(r"\.(tsx?|jsx?|json|html|md)$", value):
        return value
    return None


def collect() -> dict[str, dict]:
    files: dict[str, dict] = {}
    for md in sorted(MODULE_DIR.glob("*.md")):
        module = md.stem
        text = md.read_text(encoding="utf-8")
        # Only the first "Legacy files" table in the merged file (they are de-duplicated there).
        m = re.search(r"^## Legacy files\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
        if not m:
            continue
        for line in m.group(1).splitlines():
            row = ROW.match(line)
            if not row:
                continue
            if row.group("file").lower().startswith(("file", "---")):
                continue
            path = clean_file(row.group("file"))
            if not path:
                continue
            entry = files.setdefault(path, {"lines": set(), "modules": set()})
            entry["modules"].add(module)
            lines = row.group("lines").strip().strip("`")
            if lines and lines != "—":
                entry["lines"].add(lines)
    return files


def table(files: dict[str, dict]) -> str:
    # Group: frontend src files first, then root-level, then backend.
    def sort_key(path: str):
        tier = 0 if path.startswith("src/") else 1 if not path.startswith("backend:") else 2
        return (tier, path)

    out = [
        "| Legacy file | Length | Audited in |",
        "| --- | --- | --- |",
    ]
    for path in sorted(files, key=sort_key):
        info = files[path]
        modules = ", ".join(f"`{m}`" for m in sorted(info["modules"]))
        # Keep only the first clean number (the file's length); drop prose annotations.
        nums = []
        for value in info["lines"]:
            m = re.match(r"^\s*(\d+)\s*$", value)
            if m:
                nums.append(int(m.group(1)))
        length = str(min(nums)) if nums else "—"
        label = f"`{path}`" if not path.startswith("backend:") else f"`{path}`"
        out.append(f"| {label} | {length} | {modules} |")
    return "\n".join(out)


def main() -> int:
    files = collect()
    body = table(files)
    if "--write" not in sys.argv:
        print(body)
        return 0

    text = AUDIT.read_text(encoding="utf-8")
    header = "## 8. Appendix: legacy file → module map"
    i = text.index(header)
    rest = text[i + len(header):]
    # Keep everything up to the first "<!-- PENDING" or the first table, replace the section body.
    intro = (
        "\n\nGenerated by `scripts/build-file-map.py` from the `Legacy files` table of every\n"
        "`docs/audit/<module>.md`. One row per legacy source file, with every module that audits it.\n"
        "A file listed against several modules is shared: the first module to port it owns the shared\n"
        "helper, the others import it from `core/` or `platform/` (see `CLAUDE.md` layering rules).\n"
        "Backend files appear where a module's behaviour depends on a handler.\n\n"
    )
    text = text[: i + len(header)] + intro + body + "\n"
    AUDIT.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} rows into {AUDIT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
